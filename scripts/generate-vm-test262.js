import { parse } from 'acorn';
import { readFile, writeFile } from 'node:fs/promises';
// Eight pinned numeric tests. Assertions stay on the host; each pure failure
// predicate becomes a VM function whose expected result is false.
const cases = [];
function expression(n) {
  if (n.type === 'Literal' && typeof n.value === 'number') return n.raw;
  if (n.type === 'Identifier' && ['NaN', 'Infinity'].includes(n.name)) return n.name;
  if (n.type === 'MemberExpression' && n.object.name === 'Number' && !n.computed) {
    const value = { NaN: 'NaN', POSITIVE_INFINITY: 'Infinity', NEGATIVE_INFINITY: '(-Infinity)', MAX_VALUE: '1.7976931348623157e308', MIN_VALUE: '5e-324' }[n.property.name];
    if (value) return value;
  }
  if (n.type === 'Literal' && typeof n.value === 'boolean') return String(n.value);
  if (n.type === 'UnaryExpression') return `(${n.operator}${expression(n.argument)})`;
  if (n.type === 'BinaryExpression') return `(${expression(n.left)} ${n.operator} ${expression(n.right)})`;
  if (n.type === 'CallExpression' && n.callee.name === 'isNaN' && n.arguments.length === 1) {
    const value = expression(n.arguments[0]); return `(${value} !== ${value})`;
  }
  throw new Error(`Unexpected upstream expression: ${n.type}`);
}
for (let i = 1; i <= 8; i++) {
  const name = `S11.6.1_A4_T${i}.js`, source = await readFile(`test/fixtures/test262/${name}`, 'utf8');
  const ast = parse(source, { ecmaVersion: 2025 }); let index = 0;
  function visit(n) {
    if (n.type === 'IfStatement') {
      cases.push({ name: `Test262 ${name} predicate ${++index}`, source: `function f(x) { return ${expression(n.test)}; }` });
      if (n.alternate) visit(n.alternate);
    } else if (n.type === 'BlockStatement' || n.type === 'Program') n.body.forEach(visit);
    else throw new Error(`Unexpected upstream statement: ${n.type}`);
  }
  visit(ast);
}
await writeFile('test/vm-test262-cases.js', `/*! Adapted from Test262. Copyright 2009 the Sputnik authors. BSD-3-Clause.
 * See test/fixtures/test262/LICENSE and SOURCE.json. Generated by scripts/generate-vm-test262.js. */
export const test262Cases = ${JSON.stringify(cases, null, 2)};\n`);
console.log(`Generated ${cases.length} predicates from eight pinned numeric Test262 tests.`);
