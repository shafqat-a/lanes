// Deterministic build-time generator. Never uses JS native case conversion.
import {execFileSync} from 'node:child_process';
import {mkdtempSync,readFileSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=dirname(fileURLToPath(import.meta.url)),vendor=join(root,'vendor');
const temp=mkdtempSync(join(tmpdir(),'lanes-unicode-case-'));let raw;
try{
 execFileSync(process.env.CC||'cc',['-O2','-I',vendor,join(root,'string-case-generator.c'),join(vendor,'libunicode.c'),join(vendor,'cutils.c'),'-o',join(temp,'generate')]);
 raw=JSON.parse(execFileSync(join(temp,'generate'),[],{encoding:'utf8',maxBuffer:1<<24}));
}finally{rmSync(temp,{recursive:true,force:true});}
function compress(entries){const ranges=[],expansions=[];for(let i=0;i<entries.length;){const row=entries[i];if(row.length!==2){expansions.push([...row,...Array(4-row.length).fill(0)]);i++;continue;}const delta=row[1]-row[0];let end=row[0],step=1,j=i+1;if(j<entries.length&&entries[j].length===2&&entries[j][1]-entries[j][0]===delta&&(entries[j][0]-end===1||entries[j][0]-end===2)){step=entries[j][0]-end;while(j<entries.length&&entries[j].length===2&&entries[j][1]-entries[j][0]===delta&&entries[j][0]-end===step){end=entries[j][0];j++;}}ranges.push([row[0],end,step,delta>>>0]);i=j;}return {ranges,expansions};}
const data={version:raw.version,vendorSHA256:Object.fromEntries(['libunicode.h','libunicode.c','libunicode-table.h'].map(n=>[n,createHash('sha256').update(readFileSync(join(vendor,n))).digest('hex')])),upper:compress(raw.maps[0]),lower:compress(raw.maps[1]),flags:raw.flags};
const license=readFileSync(join(vendor,'libunicode.h'),'utf8').split('*/')[0]+'*/\n';
const header=license+'// Generated by string-case-generate.mjs from pinned vendor tables; do not edit.\n';
writeFileSync(join(root,'string-case-data.js'),header+'export const stringCaseData='+JSON.stringify(data)+';\n');
const storage=[],layout={};
function store(name,rows){const offset=storage.length/4;for(const row of rows)storage.push(...row,...Array(4-row.length).fill(0));layout[name]={offset,length:rows.length};return offset;}
for(const mode of ['upper','lower']){store(mode+'Ranges',data[mode].ranges);store(mode+'Expansions',data[mode].expansions);}
store('flags',data.flags);
writeFileSync(join(root,'string-case-buffer.js'),header+'export const stringCaseLayout='+JSON.stringify(layout)+';\nexport const stringCaseStorage=new Uint32Array('+JSON.stringify(storage)+');\n');
let wgsl='@group(0) @binding(5) var<storage, read> unicode_case_data: array<vec4<u32>>;\n';
for(const mode of ['upper','lower']){
 wgsl+=`fn unicode_${mode}(cp:u32,index:u32)->i32 {
 var lo=0u;var hi=${data[mode].expansions.length}u;
 loop{if(lo>=hi){break;}let mid=(lo+hi)/2u;let row=unicode_case_data[${layout[mode+'Expansions'].offset}u+mid];if(cp<row.x){hi=mid;}else if(cp>row.x){lo=mid+1u;}else{if(index>=3u){return -1;}let value=row[index+1u];if(value==0u){return -1;}return i32(value);}}
 if(index!=0u){return -1;}
 lo=0u;hi=${data[mode].ranges.length}u;
 loop{if(lo>=hi){break;}let mid=(lo+hi)/2u;let row=unicode_case_data[${layout[mode+'Ranges'].offset}u+mid];if(cp<row.x){hi=mid;}else if(cp>row.y){lo=mid+1u;}else{if((cp-row.x)%row.z==0u){return i32(cp+row.w);}return i32(cp);}}
 return i32(cp);
}\n`;
}

wgsl+=`fn unicodeCaseFlags(cp:u32)->u32 {
 var lo=0u;var hi=${data.flags.length}u;
 loop{if(lo>=hi){break;}let mid=(lo+hi)/2u;let row=unicode_case_data[${layout.flags.offset}u+mid];if(cp<row.x){hi=mid;}else if(cp>row.y){lo=mid+1u;}else{return row.z;}}
 return 0u;
}
fn unicodeCasePoint(cp:u32,lower:bool,index:u32)->i32 {if(lower){return unicode_lower(cp,index);}return unicode_upper(cp,index);}
`;
writeFileSync(join(root,'string-case-wgsl.js'),header+'export const stringCaseWGSL='+JSON.stringify(wgsl)+';\n');
console.log(JSON.stringify({unicodeVersion:data.version,upperMappings:raw.maps[0].length,lowerMappings:raw.maps[1].length,upperRanges:data.upper.ranges.length,upperExpansions:data.upper.expansions.length,lowerRanges:data.lower.ranges.length,lowerExpansions:data.lower.expansions.length,propertyRanges:data.flags.length,wgslBytes:wgsl.length,storageBytes:storage.length*4}));
